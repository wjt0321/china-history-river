/** 转 GeoJSON Feature */
function toFeature(t: DynastyTerritory) {
  return {
    type: 'Feature',
    properties: {
      id: t.id,
      name: t.name,
      peakYear: t.peakYear,
    },
    geometry: {
      type: 'Polygon',
      coordinates: [
        // GeoJSON 闭合多边形需要首尾相同
        [...t.polygon, t.polygon[0]],
      ],
    },
  }
}

const collection = {
  type: 'FeatureCollection',
  features: TERRITORIES.map(toFeature),
}

// 写总集
fs.writeFileSync(
  path.join(OUT_DIR, 'all.json'),
  JSON.stringify(collection, null, 2),
  'utf-8',
)

// 写单个文件
for (const t of TERRITORIES) {
  fs.writeFileSync(
    path.join(OUT_DIR, `${t.id}.json`),
    JSON.stringify(toFeature(t), null, 2),
    'utf-8',
  )
}

